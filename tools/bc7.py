class Bits:
    def __init__(s, b): s.v = int.from_bytes(b, "little"); s.p = 0
    def r(s, n):
        x = (s.v >> s.p) & ((1 << n) - 1); s.p += n; return x

def interp(a, b, w): return ((64 - w) * a + w * b + 32) >> 6

def block(b):
    bits = Bits(b)
    m = 0
    while m < 8 and not bits.r(1): m += 1
    if m == 8: return np.zeros((16, 4), np.uint8)
    ns, pb, rb, isb, cb, ab, pbt, ib, ib2 = MODES[m]
    part = bits.r(pb); rot = bits.r(rb); isel = bits.r(isb)
    ne = ns * 2
    ep = [[0, 0, 0, 0] for _ in range(ne)]
    for c in range(3):
        for e in range(ne): ep[e][c] = bits.r(cb)
    for e in range(ne): ep[e][3] = bits.r(ab) if ab else 0
    cbits, abits = cb, ab
    if pbt == "e":
        for e in range(ne):
            p = bits.r(1)
            for c in range(4): ep[e][c] = (ep[e][c] << 1) | p
        cbits += 1; abits = abits + 1 if ab else 0
    elif pbt == "s":
        for s in range(ns):
            p = bits.r(1)
            for e in (2 * s, 2 * s + 1):
                for c in range(3): ep[e][c] = (ep[e][c] << 1) | p
        cbits += 1
    for e in range(ne):
        for c in range(3): ep[e][c] = (ep[e][c] << (8 - cbits)) | (ep[e][c] >> (2 * cbits - 8))
        ep[e][3] = ((ep[e][3] << (8 - abits)) | (ep[e][3] >> (2 * abits - 8))) if ab else 255
    if ns == 1: sub = [0] * 16; anch = [0]
    elif ns == 2: sub = [(P2[part] >> i) & 1 for i in range(16)]; anch = [0, A2[part]]
    else: sub = [int(ch) for ch in P3[part]]; anch = [0, A3a[part], A3b[part]]
    idx = []
    for i in range(16):
        n = ib - (1 if i in anch else 0)
        idx.append(bits.r(n))
    idx2 = []
    if ib2:
        for i in range(16): idx2.append(bits.r(ib2 - (1 if i == 0 else 0)))
    out = np.zeros((16, 4), np.uint8)
    for i in range(16):
        s = sub[i]; e0, e1 = ep[2 * s], ep[2 * s + 1]
        if ib2:
            ci, ai, cw, aw = (idx2[i], idx[i], ib2, ib) if isel else (idx[i], idx2[i], ib, ib2)
        else:
            ci = ai = idx[i]; cw = aw = ib
        px = [interp(e0[c], e1[c], W[cw][ci]) for c in range(3)] + [interp(e0[3], e1[3], W[aw][ai])]
        if rot: px[3], px[rot - 1] = px[rot - 1], px[3]
        out[i] = px
    return out

def decode(data, w, h):
    img = np.zeros((h, w, 4), np.uint8); k = 0
    for by in range(0, h, 4):
        for bx in range(0, w, 4):
            img[by:by + 4, bx:bx + 4] = block(data[k:k + 16]).reshape(4, 4, 4); k += 16
    return img
